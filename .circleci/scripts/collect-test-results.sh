#!/usr/bin/env bash
#
#   collect-test-results.sh <destination>
#
# Gathers each package's JUnit report into one directory for store_test_results,
# which takes a single path rather than a glob.
#
# Classnames are prefixed with the package directory on the way through.
# CircleCI identifies a test by (classname, name), and vitest sets classname to
# the test file's package-relative path — `src/junk.test.ts` exists in both
# @osdk/api and @osdk/version-updater, and there are 13 such collisions in this
# repo. Unprefixed, CircleCI would merge unrelated tests in the summary and,
# worse, flaky detection would read "passed here, failed there" as one flaky
# test.

set -euo pipefail

dest="${1:?usage: collect-test-results.sh <destination>}"
mkdir -p "$dest"

count=0
while IFS= read -r report; do
  pkg="$(basename "$(dirname "$(dirname "$report")")")"
  # The input is machine-generated by vitest, so a targeted attribute rewrite is
  # safe here in a way it would not be for hand-written XML. Inputs go through
  # the environment rather than argv, because `node -e` shifts positional
  # arguments down by one and that is an easy thing to get subtly wrong.
  # The `$1` below is a regex backreference for String.replace, not a shell
  # positional, so the single quotes are deliberate.
  # shellcheck disable=SC2016
  REPORT="$report" PKG="$pkg" node -e '
    const fs = require("node:fs");
    const xml = fs.readFileSync(process.env.REPORT, "utf8");
    process.stdout.write(
      xml.replace(/classname="([^"]*)"/g, `classname="${process.env.PKG}/$1"`),
    );
  ' > "$dest/$pkg.xml"
  count=$((count + 1))
done < <(find packages -path '*/reports/junit.xml' -type f 2>/dev/null | sort)

echo "Collected $count JUnit report(s) into $dest."

# Not an error: a container whose whole share was a turbo cache hit still has
# reports, but one that halted early or ran no matching packages will not.
if [ "$count" -eq 0 ]; then
  echo "No JUnit reports found — nothing to upload."
fi
