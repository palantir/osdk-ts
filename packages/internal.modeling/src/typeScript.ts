import {
  type JsonSchema,
  type ModelDocuments,
  referenceName,
  validateDocuments,
} from "./jsonSchema.js";

/** Emits standalone model declarations with named recursive edges and shallow readonly boundaries. */
export function generateTypeScript(documents: ModelDocuments): string {
  validateDocuments(documents);

  function type(schema: JsonSchema): string {
    let value: string;
    if (schema.$ref) {
      value = referenceName(schema.$ref, documents);
    } else if ("const" in schema) {
      value = JSON.stringify(schema.const);
    } else if (schema.enum) {
      value = schema.enum.map((entry) => JSON.stringify(entry)).join(" | ");
    } else if (schema.anyOf ?? schema.oneOf) {
      value = (schema.anyOf ?? schema.oneOf ?? [])
        .map((entry) => type(entry as JsonSchema))
        .join(" | ");
    } else {
      switch (schema.type) {
        case "string":
          value = "string";
          break;
        case "number":
        case "integer":
          value = "number";
          break;
        case "boolean":
          value = "boolean";
          break;
        case "array":
          if (schema.prefixItems !== undefined) {
            return `${schema.readOnly ? "readonly " : ""}[${schema.prefixItems.map((item) => type(item as JsonSchema)).join(", ")}]`;
          }

          return `${schema.readOnly ? "ReadonlyArray" : "Array"}<${type(schema.items as JsonSchema)}>`;
        case "object":
          if (typeof schema.additionalProperties === "object") {
            value = `Record<string, ${type(schema.additionalProperties)}>`;
          } else {
            return `{\n${Object.entries(schema.properties ?? {})
              .map(
                ([name, child]) =>
                  `  ${schema.readOnly ? "readonly " : ""}${JSON.stringify(name)}${schema.required?.includes(name) ? "" : "?"}: ${type(child as JsonSchema)};`,
              )
              .join("\n")}\n}`;
          }

          break;
        default:
          throw new Error("Unsupported model representation");
      }
    }

    return schema.readOnly &&
      (schema.$ref || schema.type === "object" || schema.anyOf || schema.oneOf)
      ? `Readonly<${value}>`
      : value;
  }
  // end of inline type() function declaration

  const sourceCode = Object.entries(documents)
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([name, schema]) => `export type ${name} = ${type(schema)};\n`)
    .join("\n");

  return `// @generated by @osdk/internal.modeling. Do not edit.\n\n${sourceCode}`;
}
