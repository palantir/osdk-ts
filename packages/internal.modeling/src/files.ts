import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

/** Checks every output before writing; check mode never changes files. JSON outputs are explicitly owned by the caller. */
export function synchronizeModelFiles(
  files: ReadonlyMap<string, string>,
  mode: "write" | "check",
): void {
  const changed: [string, string][] = [];
  for (const [path, expected] of files) {
    const existing = existsSync(path) ? readFileSync(path, "utf-8") : undefined;
    if (existing === expected) continue;
    if (
      existing !== undefined &&
      !path.endsWith(".json") &&
      !existing
        .replace(/^\/\*[\s\S]*?\*\/\s*/u, "")
        .startsWith(
          path.endsWith(".py")
            ? "# @generated by @osdk/internal.modeling."
            : "// @generated by @osdk/internal.modeling.",
        )
    ) {
      throw new Error(`Refusing to overwrite handwritten file: ${path}`);
    }
    if (mode === "check") throw new Error(`Stale generated model: ${path}`);
    changed.push([path, expected]);
  }
  for (const [path, expected] of changed) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, expected);
  }
}
