import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { expect, it } from "vitest";

import { synchronizeModelFiles } from "./files.js";

it("checks generated output ownership without partial writes", async () => {
  const directory = await mkdtemp(join(tmpdir(), "modeling-files-"));
  try {
    const generated = join(directory, "models.ts");
    const handwritten = join(directory, "handwritten.ts");
    await writeFile(handwritten, "export type Original = string;\n");
    const files = new Map([
      [generated, "// @generated by @osdk/internal.modeling. Do not edit.\n"],
      [handwritten, "replacement"],
    ]);
    expect(() => synchronizeModelFiles(files, "write")).toThrow(
      "handwritten file",
    );
    await expect(readFile(generated)).rejects.toThrow();
    files.delete(handwritten);
    expect(() => synchronizeModelFiles(files, "check")).toThrow(
      "Stale generated model",
    );
    await expect(readFile(generated)).rejects.toThrow();
    synchronizeModelFiles(files, "write");
    expect(() => synchronizeModelFiles(files, "check")).not.toThrow();
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});
